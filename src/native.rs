#[derive(Deserialize)]
struct ReplayJob {
    lib: PathBuf,
    cases: PathBuf,
    meta: PathBuf,
    func: String,
    out: PathBuf,
    /// Go: a nil slice or map records as null; the port's empty Vec is the same thing.
    #[serde(default)]
    loose_empty: bool,
    #[serde(default = "half")]
    budget: f64,
}

fn half() -> f64 {
    0.5
}

/// Build-and-check for C-bridge ports: replays the recordings in a child process.
pub fn verify(ctx: &Ctx, port: &Port, loose_empty: bool) -> Result<Verify> {
    let dir = ctx.crate_dir(port);
    let (_, lib) = port.lang.artifact(&port.ext);
    let replay = backend::replay(ctx, port)?;
    let out = replay.out;
    let _ = fs::remove_file(&out);
    let job = json!({
        "lib": ctx.lib_dir().join(lib), "cases": replay.cases, "meta": dir.join("recordings.meta.json"),
        "func": port.func, "out": out, "loose_empty": loose_empty,
    });
    let job_path = dir.join("job-verify.json");
    fs::write(&job_path, serde_json::to_vec_pretty(&job)?)?;
    let me = std::env::current_exe().context("finding fast-anything itself")?;
    let run = output(Command::new(me).arg("__replay").arg(&job_path), "fast-anything")?;
    let mut v = if run.status.success() && out.exists() {
        serde_json::from_str::<Verify>(&fs::read_to_string(&out)?).context("reading verify results")?
    } else {
        let total = util::count_lines(&replay.cases);
        Verify {
            total,
            failed: total,
            failures: vec![Failure {
                case: 0,
                call: format!("{}(...) (replaying the recorded calls)", port.func),
                expected: "the same results".into(),
                got: format!("the port crashed ({}): {}", run.status, tail(&combined(&run), 12)),
            }],
            ..Verify::default()
        }
    };
    v.built = true;
    Ok(v)
}

type FaCall = unsafe extern "C" fn(*const u8, usize, *mut usize) -> *mut u8;
type FaFree = unsafe extern "C" fn(*mut u8, usize);
type FaTime = unsafe extern "C" fn(*const u8, usize, f64) -> f64;

fn show(v: &Value, limit: usize) -> String {
    let s = v.to_string();
    if s.chars().count() <= limit { s } else { format!("{}…", s.chars().take(limit - 1).collect::<String>()) }
}

/// The hidden  fast-anything __replay <job>  command.
pub fn replay(job_path: &Path) -> Result<()> {
    let job: ReplayJob = serde_json::from_str(&fs::read_to_string(job_path)?).context("reading the replay job")?;
    // SAFETY: the library is the port fast-anything just built; its entry points have these signatures.
    let lib =
        unsafe { libloading::Library::new(&job.lib) }.with_context(|| format!("loading {}", job.lib.display()))?;
    // C ports also take plain C values (see cfamily/typed.rs): replay and time that, as the app calls it
    let call: libloading::Symbol<FaCall> =
        unsafe { lib.get(b"fa_call_typed").or_else(|_| lib.get(b"fa_call")) }.context("fa_call missing")?;
    let free: libloading::Symbol<FaFree> = unsafe { lib.get(b"fa_free") }.context("fa_free missing")?;
    let time: Option<libloading::Symbol<FaTime>> = unsafe { lib.get(b"fa_time_typed") }.ok();
    let invoke = |input: &[u8]| -> std::result::Result<Value, String> {
        let mut n = 0usize;
        let bytes = unsafe {
            let p = call(input.as_ptr(), input.len(), &mut n);
            let bytes = std::slice::from_raw_parts(p, n).to_vec();
            free(p, n);
            bytes
        };
        let reply: Value = serde_json::from_slice(&bytes).map_err(|e| format!("bad reply: {e}"))?;
        match reply.get("error") {
            Some(e) => Err(e.as_str().map(str::to_string).unwrap_or_else(|| e.to_string())),
            None => Ok(reply.get("ok").cloned().unwrap_or(Value::Null)),
        }
    };

    let text = fs::read_to_string(&job.cases).context("reading the recorded calls")?;
    let cases: Vec<Value> =
        text.lines().filter(|l| !l.trim().is_empty()).filter_map(|l| serde_json::from_str(l).ok()).collect();
    let (mut passed, mut failed, mut derived, mut edges) = (0, 0, 0, 0);
    let mut failures = Vec::new();
    let mut inputs = Vec::new();
    let mut typed_inputs = Vec::new();
    for (i, case) in cases.iter().enumerate() {
        let input = serde_json::to_vec(&case["args"])?;
        let is_derived = case.get("derived").is_some();
        let is_edge = case["derived"] == "edge";
        if is_derived {
            derived += 1;
            edges += usize::from(is_edge);
        } else {
            inputs.push(input.clone());
            typed_inputs.push(&case["args"]);
        }
        let got = invoke(&input);
        let (ok, expected) = match case.get("raises") {
            Some(e) => (got.is_err(), format!("fails with {}", e.as_str().unwrap_or("an error"))),
            None => {
                let want = &case["result"];
                (got.as_ref().is_ok_and(|g| same(want, g, job.loose_empty)), show(want, 160))
            }
        };
        if ok {
            passed += 1;
            continue;
        }
        failed += 1;
        if failures.len() < 8 {
            let args: Vec<String> =
                case["args"].as_array().map(|a| a.iter().map(|v| show(v, 80)).collect()).unwrap_or_default();
            failures.push(Failure {
                case: i,
                call: format!(
                    "{}{}({})",
                    if is_edge {
                        "(edge) "
                    } else if is_derived {
                        "(derived) "
                    } else {
                        ""
                    },
                    job.func,
                    args.join(", ")
                ),
                expected,
                got: match got {
                    Ok(v) => show(&v, 160),
                    Err(e) => format!("error: {}", show(&Value::String(e), 200)),
                },
            });
        }
    }

    let mut v = Verify { total: cases.len(), derived, edges, passed, failed, failures, ..Verify::default() };
    let original_ns = fs::read_to_string(&job.meta)
        .ok()
        .and_then(|t| serde_json::from_str::<Value>(&t).ok())
        .and_then(|m| m["original_ns"].as_f64());
    if let Some(original_ns) = original_ns.filter(|n| *n > 0.0 && failed == 0 && !inputs.is_empty()) {
        let rust_ns = match &time {
            Some(time) => {
                let all = serde_json::to_vec(&typed_inputs)?;
                unsafe { time(all.as_ptr(), all.len(), job.budget) }
            }
            None => {
                let (mut best, mut spent, mut passes) = (f64::INFINITY, 0.0, 0);
                while passes < 3 || (spent < job.budget && passes < 2000) {
                    let t = Instant::now();
                    for input in &inputs {
                        let _ = std::hint::black_box(invoke(input));
                    }
                    let took = t.elapsed().as_secs_f64();
                    best = best.min(took);
                    spent += took;
                    passes += 1;
                }
                best / inputs.len() as f64 * 1e9
            }
        };
        if rust_ns >= 0.0 {
            let speedup = if rust_ns > 0.0 { original_ns / rust_ns } else { 0.0 };
            v.micro = Some(Micro { original_ns, rust_ns, speedup, clock_ns: clock_ns() });
        }
    }
    fs::write(&job.out, serde_json::to_vec(&v)?)?;
    Ok(())
}

/// What one clock read costs here: the average of ten thousand back-to-back reads (a single read
/// can come out as 0 on a coarse clock, as on macOS). The recorders time each call of the original
/// with a read before and after it, so about this much of original_ns is the clock.
fn clock_ns() -> f64 {
    const READS: u32 = 10_000;
    let start = Instant::now();
    for _ in 0..READS {
        std::hint::black_box(Instant::now());
    }
    start.elapsed().as_secs_f64() * 1e9 / f64::from(READS)
}

/// Same value, give or take float rounding.
pub fn same(a: &Value, b: &Value, loose_empty: bool) -> bool {
    same_in(a, b, 0.0, loose_empty)
}

/// `scale`: the largest finite magnitude in the expected array holding `a` (0 outside arrays).
fn same_in(a: &Value, b: &Value, scale: f64, loose_empty: bool) -> bool {
    match (a, b) {
        (Value::Number(x), Value::Number(y)) => {
            if x.is_f64() || y.is_f64() {
                close(x.as_f64().unwrap_or(f64::NAN), y.as_f64().unwrap_or(f64::NAN), scale)
            } else {
                x == y
            }
        }
        (Value::Array(x), Value::Array(y)) => {
            let scale = x.iter().filter_map(Value::as_f64).filter(|v| v.is_finite()).fold(0.0, |m, v| v.abs().max(m));
            x.len() == y.len() && x.iter().zip(y).all(|(p, q)| same_in(p, q, scale, loose_empty))
        }
        (Value::Object(x), Value::Object(y)) => {
            x.len() == y.len() && x.iter().all(|(k, p)| y.get(k).is_some_and(|q| same_in(p, q, 0.0, loose_empty)))
        }
        (Value::Null, Value::Array(v)) | (Value::Array(v), Value::Null) => loose_empty && v.is_empty(),
        (Value::Null, Value::Object(v)) | (Value::Object(v), Value::Null) => loose_empty && v.is_empty(),
        (Value::Array(a), Value::Object(o)) | (Value::Object(o), Value::Array(a)) => {
            loose_empty && a.is_empty() && o.is_empty()
        }
        _ => a == b,
    }
}

/// Floats within 1e-9 of their size (or of `scale`). -0.0 isn't 0.0: it prints differently.
fn close(x: f64, y: f64, scale: f64) -> bool {
    if x.is_nan() || y.is_nan() {
        return x.is_nan() && y.is_nan();
    }
    if x == y {
        return x.is_sign_negative() == y.is_sign_negative();
    }
    x.is_finite() && y.is_finite() && (x - y).abs() <= 1e-9 * x.abs().max(y.abs()).max(scale)
}

